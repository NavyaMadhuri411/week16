risk_analysis = """
=== Ethical Risk Analysis ===

Risk 1: Prompt injection
A malicious user or retrieved document may try to override
the assistant's instructions.
Mitigation: Separate trusted instructions from retrieved content,
treat retrieved text as untrusted, and test adversarial inputs.
Prompt wording alone is not a complete security boundary.

Risk 2: Hallucination
The model may generate unsupported climate claims.
Mitigation: Ground answers in retrieved sources, allow abstention,
verify important claims, and evaluate faithfulness.

Risk 3: Bias and incomplete information
The knowledge base may omit relevant regions, communities,
or scientific perspectives.
Mitigation: Use diverse authoritative sources, review coverage,
and regularly update the knowledge base.

Risk 4: False confidence in evaluation scores
Keyword-based metrics do not fully measure semantic correctness.
Mitigation: Use expert review and a suitable RAGAS evaluation
with a judge model when API access is available.
"""

