# STEP 4: Simplified manual evaluation metrics
# --------------------------------------------------

def faithfulness_score(sample, version):
    """
    Manual annotation:
    supported claims / total claims.
    Scores are between 0 and 1.
    """
    supported = sample["supported_claims"][version]
    total = sample["total_claims"][version]
    return supported / total if total else 0.0


def relevancy_score(sample, version):
    """
    Keyword-based approximation:
    matched relevant terms / total relevant terms.
    This is not an actual RAGAS answer_relevancy score.
    """
    answer = sample["answers"][version].lower()
    terms = sample["relevance_terms"]

    matched = sum(
        1 for term in terms if term.lower() in answer
    )

    return matched / len(terms) if terms else 0.0


